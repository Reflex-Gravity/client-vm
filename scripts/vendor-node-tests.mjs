// Refreshes test/conformance/node-tests from a Node.js checkout and a
// discovery run's results: every test that passed is copied byte for byte,
// with test/common, the fixtures those tests reference, and Node's LICENSE.
// test/e2e/node-tests.spec.ts runs the set in CI. Usage:
//   NODE_SRC=<node checkout at v24.11.0> node scripts/vendor-node-tests.mjs results.json
import {
  cpSync,
  existsSync,
  mkdirSync,
  readFileSync,
  rmSync,
  statSync,
  writeFileSync,
} from 'node:fs';
import { dirname, join, relative } from 'node:path';

const SRC = process.env.NODE_SRC;
const results = JSON.parse(readFileSync(process.argv[2], 'utf8'));
const OUT = new URL('../test/conformance/node-tests', import.meta.url).pathname;
if (!SRC) throw new Error('NODE_SRC must point at a Node.js checkout');

const copy = (rel) => {
  const from = join(SRC, rel);
  if (!existsSync(from)) return;
  const to = join(OUT, rel.replace(/^test\//, ''));
  mkdirSync(dirname(to), { recursive: true });
  cpSync(from, to, { recursive: true });
};

/** Fixture paths a test references (the same rules as the discovery runner). */
function fixtures(source) {
  const out = new Set();
  for (const m of source.matchAll(
    /fixtures\.(?:path|readSync|readKey|fileURL|toDataURL)\(\s*([^)]*)\)/g,
  )) {
    const parts = [...m[1].matchAll(/'([^']*)'|"([^"]*)"/g)].map((x) => x[1] ?? x[2]);
    if (parts.length === 0) continue;
    const base = m[0].includes('readKey') ? 'test/fixtures/keys' : 'test/fixtures';
    out.add(join(base, ...parts));
  }
  for (const m of source.matchAll(/['"]\.\.\/fixtures\/([^'"]+)['"]/g))
    out.add(join('test/fixtures', m[1]));
  return [...out].filter((p) => {
    const abs = join(SRC, p);
    if (!existsSync(abs)) return false;
    const st = statSync(abs);
    return st.isDirectory() || st.size <= 2_000_000;
  });
}

rmSync(OUT, { recursive: true, force: true });
mkdirSync(OUT, { recursive: true });
const passed = Object.entries(results)
  .filter(([, r]) => r.status === 'pass')
  .map(([f]) => f)
  .sort();
const skipped = Object.entries(results)
  .filter(([, r]) => r.status === 'skip')
  .map(([f]) => f)
  .sort();
copy('test/common');
copy('LICENSE');
cpSync(join(SRC, 'LICENSE'), join(OUT, 'LICENSE'));
mkdirSync(join(OUT, 'fixtures'), { recursive: true });
writeFileSync(join(OUT, 'fixtures', 'empty.js'), '');
for (const f of passed) {
  copy(`test/parallel/${f}`);
  for (const fx of fixtures(readFileSync(join(SRC, 'test/parallel', f), 'utf8'))) copy(fx);
}
const byModule = {};
for (const [f, r] of Object.entries(results)) {
  const m = f.replace(/^test-/, '').split(/[-.]/)[0];
  byModule[m] ??= { pass: 0, fail: 0, skip: 0 };
  byModule[m][r.status]++;
}
writeFileSync(
  join(OUT, 'manifest.json'),
  `${JSON.stringify({ node: 'v24.11.0', note: 'Generated by scripts/vendor-node-tests.mjs', passing: passed, byModule }, null, 1)}\n`,
);
writeFileSync(
  join(OUT, 'README.md'),
  `# Node.js test/parallel subset\n\nTests from Node.js v24.11.0 \`test/parallel\` (with \`test/common\` and the fixtures they use) that\npass inside ClientVM, copied unmodified. Node.js is MIT-licensed; see LICENSE. \`manifest.json\`\nlists the passing set and per-module counts from the last discovery run. Regenerate with\n\`scripts/vendor-node-tests.mjs\`; \`test/e2e/node-tests.spec.ts\` runs them.\n`,
);
console.log(
  `vendored ${passed.length} passing tests (${skipped.length} skipped) into ${relative(process.cwd(), OUT)}`,
);
