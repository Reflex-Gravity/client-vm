function unsupported(what: string): never {
  const err = new Error(
    `http2.${what} is not available in ClientVM (browsers do not expose raw sockets); use http, https or fetch`,
  );
  (err as { code?: string }).code = 'ERR_CLIENTVM_UNSUPPORTED';
  throw err;
}

export function createHttp2(): Record<string, unknown> {
  const constants: Record<string, string | number> = { ...OTHER };
  for (const h of HEADERS) {
    constants[`HTTP2_HEADER_${h.replace(/^:/, '').toUpperCase().replace(/-/g, '_')}`] = h;
  }
  for (const m of METHODS) constants[`HTTP2_METHOD_${m.replace(/-/g, '_')}`] = m;
  for (const [n, name] of STATUSES) constants[`HTTP_STATUS_${name}`] = n;
  return {
    constants,
    connect: () => unsupported('connect'),
    createServer: () => unsupported('createServer'),
    createSecureServer: () => unsupported('createSecureServer'),
    getDefaultSettings: () => ({
      headerTableSize: 4096,
      enablePush: true,
      initialWindowSize: 65535,
      maxFrameSize: 16384,
      maxConcurrentStreams: 4294967295,
      maxHeaderListSize: 65535,
      maxHeaderSize: 65535,
      enableConnectProtocol: false,
    }),
    getPackedSettings: () => new Uint8Array(0),
    getUnpackedSettings: () => ({}),
    sensitiveHeaders: Symbol('nodejs.http2.sensitiveHeaders'),
  };
}
